//go:build !quire_nobake

package app

import (
	"encoding/json/v2"
	"fmt"
	"os"
	"path/filepath"

	"github.com/lahickey/quire"
	"github.com/lahickey/quire/bake"
	"github.com/lahickey/quire/model"
	"github.com/lahickey/quire/pack/base/convert"
)

const canBake = true

const shipGo = `// Code generated by the bake. DO NOT EDIT.

package main

import (
	"embed"

	"github.com/lahickey/quire/app"
)

//go:embed all:%[1]s
var bundle embed.FS

func init() { app.Ship(bundle, %[1]q) }
`

func writeShip(s model.BakeSpec) error {
	src := filepath.Join(s.Dir, "ship.go")
	overlay, err := json.Marshal(map[string]map[string]string{"Replace": {"ship.go": src}})
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(s.Dir, "ship.json"), overlay, 0o644); err != nil {
		return err
	}
	return os.WriteFile(src, fmt.Appendf(nil, shipGo, filepath.ToSlash(s.Bundle())), 0o644)
}

func bakeSite(id model.Identity, b quire.Blueprint, opts []quire.Option) error {
	spec := model.BakeSpec{}.WithDefaults()
	if fi, err := os.Stat(spec.Content); err != nil || !fi.IsDir() {
		spec.Content = ""
	}
	baker, err := bake.Start(spec, convert.Standard())
	if err != nil {
		return err
	}
	if err := quire.Collect(id, baker, b, opts...); err != nil {
		return err
	}
	if _, err := baker.Finish(); err != nil {
		return err
	}
	return writeShip(spec)
}
