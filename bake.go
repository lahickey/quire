//go:build !quire_nobake

package quire

import (
	"encoding/json/v2"
	"fmt"
	"os"
	"path/filepath"

	"github.com/lahickey/quire/internal/bake"
	"github.com/lahickey/quire/internal/journal"
	"github.com/lahickey/quire/model"
)

const canBake = true

const shipGo = `// Code generated by the bake. DO NOT EDIT.

package main

import (
	"embed"

	"github.com/lahickey/quire"
)

//go:embed all:%[1]s
var bundle embed.FS

func init() { quire.Ship(bundle, %[1]q) }
`

func writeShip(s model.BakeSpec) error {
	src := filepath.Join(s.Dir, "ship.go")
	overlay, err := json.Marshal(map[string]map[string]string{"Replace": {"ship.go": src}})
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(s.Dir, "ship.json"), overlay, 0o644); err != nil {
		return err
	}
	return os.WriteFile(src, fmt.Appendf(nil, shipGo, filepath.ToSlash(s.Bundle())), 0o644)
}

func (e *Engine) bake(mount func(*Engine) error) error {
	s := e.bakeSpec.WithDefaults()
	if fi, err := os.Stat(s.Content); err != nil || !fi.IsDir() {
		s.Content = ""
	}
	b, err := bake.Start(s)
	if err != nil {
		return err
	}
	e.from = b
	if err := mount(e); err != nil {
		return err
	}
	if err := b.Card(journal.SiteCard, e.siteCardText()); err != nil {
		return err
	}
	if err := b.Finish(); err != nil {
		return err
	}
	return writeShip(s)
}
