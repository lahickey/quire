//go:build !quire_nobake

package quire

import (
	"encoding/json/v2"
	"fmt"
	"os"
	"path/filepath"

	"github.com/lahickey/quire/bake"
	"github.com/lahickey/quire/model"
	"github.com/lahickey/quire/pack/base/convert"
	"github.com/lahickey/quire/site"
)

const canBake = true

var sets = []bake.Tools{convert.Standard()}

const shipGo = `// Code generated by the bake. DO NOT EDIT.

package main

import (
	"embed"

	"github.com/lahickey/quire"
)

//go:embed all:%[1]s
var bundle embed.FS

func init() { quire.Ship(bundle, %[1]q) }
`

func writeShip(s model.BakeSpec) error {
	src := filepath.Join(s.Dir, "ship.go")
	overlay, err := json.Marshal(map[string]map[string]string{"Replace": {"ship.go": src}})
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(s.Dir, "ship.json"), overlay, 0o644); err != nil {
		return err
	}
	return os.WriteFile(src, fmt.Appendf(nil, shipGo, filepath.ToSlash(s.Bundle())), 0o644)
}

// Converters adds to what Run's bake can convert, beyond base's own: a pack's converters, or a site's.
// Only a binary that can bake has it, so call it from a file with the build constraint !quire_nobake.
func Converters(more ...bake.Tools) { sets = append(sets, more...) }

func bakeSite(d *site.Description) error {
	spec := model.BakeSpec{}.WithDefaults()
	if fi, err := os.Stat(spec.Content); err != nil || !fi.IsDir() {
		spec.Content = ""
	}
	baker, err := bake.Start(spec, sets...)
	if err != nil {
		return err
	}
	if err := d.Collect(baker); err != nil {
		return err
	}
	if _, err := baker.Finish(); err != nil {
		return err
	}
	return writeShip(spec)
}
