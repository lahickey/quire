//go:build !quire_nobake

package quire

import (
	"encoding/json/v2"
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/lahickey/quire/bake"
	"github.com/lahickey/quire/model"
	"github.com/lahickey/quire/pack/base/convert"
	"github.com/lahickey/quire/site"
)

const (
	canBake = true
	shipGo  = `// Code generated by the bake. DO NOT EDIT.

package main

import (
	"embed"

	"github.com/lahickey/quire"
)

//go:embed %s
var bundles embed.FS

func init() { quire.Ship(bundles) }
`
)

var (
	sets      = []bake.Tools{convert.Standard()}
	bakedDirs []string
)

// writeShip writes the ship.go that embeds every bundle this run has baked, and the overlay that adds it to a build.
func writeShip() error {
	src := filepath.Join(model.QuireDir, "ship.go")
	overlay, err := json.Marshal(map[string]map[string]string{"Replace": {"ship.go": src}})
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(model.QuireDir, "ship.json"), overlay, 0o644); err != nil {
		return err
	}
	embeds := make([]string, len(bakedDirs))
	for i, dir := range bakedDirs {
		embeds[i] = "all:" + filepath.ToSlash(dir)
	}
	return os.WriteFile(src, fmt.Appendf(nil, shipGo, strings.Join(embeds, " ")), 0o644)
}

// Converters adds to what a bake can convert, beyond base's own: a pack's converters, or a site's.
// Only a binary that can bake has it, so call it from a file with the build constraint !quire_nobake.
func Converters(more ...bake.Tools) { sets = append(sets, more...) }

// Bake bakes a site's content into the folder spec names, and writes the ship.go that embeds every bundle this run has baked.
// A program with several sites bakes each, under a folder of its own beneath .quire.
func Bake(d *site.Description, spec model.BakeSpec) error {
	spec = spec.WithDefaults()
	if fi, err := os.Stat(spec.Content); err != nil || !fi.IsDir() {
		spec.Content = ""
	}
	baker, err := bake.Start(spec, sets...)
	if err != nil {
		return err
	}
	if err := d.Collect(baker); err != nil {
		return err
	}
	if _, err := baker.Finish(); err != nil {
		return err
	}
	if !slices.Contains(bakedDirs, spec.Bundle()) {
		bakedDirs = append(bakedDirs, spec.Bundle())
	}
	if err := os.MkdirAll(model.QuireDir, 0o755); err != nil {
		return err
	}
	return writeShip()
}
